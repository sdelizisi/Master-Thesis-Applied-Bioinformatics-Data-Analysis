#!/usr/bin/env python3
# === Random Forest Feature Stability, Aggregation & Rank Pipeline ===
# This script aggregates the 100 Random Forest output files and computes 
# the occurrence frequency, mean importance score, and mean rank position 
# for each gene across all successful iterations.

import os
import glob
import pandas as pd
import numpy as np

def main():
    # 1. Define folder paths and filenames
    base_dir = r"C:\Users\User\Desktop\Soultana\Msc Bioinformatics\Διπλωματική-Msc\07_Miscellaneous\Sfikakis_Yavropoulou\RNA-seq\files"
    input_subfolder = os.path.join(base_dir, "RF_100_Runs_Robustness_with_AUC")
    output_file_path = os.path.join(base_dir, "RF_Unified_100_Runs_Consistency_with_Rank_Table.txt")
    
    # Locate the 100 importance text files generated by the RF runs
    search_path = os.path.join(input_subfolder, "RF_run_*_importance.txt")
    all_files = glob.glob(search_path)
    total_files = len(all_files)
    
    print(f"Found {total_files} importance score files.")
    if total_files == 0:
        print("Error: No matching files found. Check your directory and filenames.")
        return

    # Dictionaries to accumulate metrics across all runs
    gene_counts = {}        # Number of times a gene appeared with an Importance_Score > 0
    gene_total_scores = {}  # Cumulative sum of Importance_Scores for mean computation
    gene_total_ranks = {}   # Cumulative sum of rank positions 

    print("\nProcessing files and calculating frequencies and average ranks...")

    # 2. Iterate through each run's output file
    for file_path in all_files:
        df = pd.read_csv(file_path, sep='\t')
        
        df['Rank'] = range(1, len(df) + 1)
        
        # Keep only active features that were actually utilized in this split 
        df_active = df[df['Importance_Score'] > 0]
        
        for _, row in df_active.iterrows():
            gene = str(row['Gene_Symbol']).strip()
            score = float(row['Importance_Score'])
            rank = int(row['Rank'])
            
            if gene in gene_counts:
                gene_counts[gene] += 1
                gene_total_scores[gene] += score
                gene_total_ranks[gene] += rank  
            else:
                gene_counts[gene] = 1
                gene_total_scores[gene] = score
                gene_total_ranks[gene] = rank

    # 3. Construct the consolidated output dataset
    unique_genes = list(gene_counts.keys())
    
    frequencies = [gene_counts[g] for g in unique_genes]
    
    # Calculate Mean Importance Score across all 100 iterations
    average_scores = [gene_total_scores[g] / total_files for g in unique_genes]
    
    # Calculate Mean Rank Position strictly based on active runs 
    mean_ranks = [gene_total_ranks[g] / gene_counts[g] for g in unique_genes]

    df_unified = pd.DataFrame({
        'Gene_Symbol': unique_genes,
        'Total_Occurrences_Out_of_100': frequencies,
        'Mean_Importance_Score': average_scores,
        'Mean_Rank_Position': mean_ranks  # The average rank metric requested by the supervisor
    })

    # 4. Sort the unified results
    df_unified = df_unified.sort_values(
        by=['Total_Occurrences_Out_of_100', 'Mean_Rank_Position'], 
        ascending=[False, True]
    )

    # 5. Save the aggregated table to a tab-separated text file
    df_unified.to_csv(output_file_path, sep='\t', index=False)
    
    print("\n> UNIFICATION & RANKING PIPELINE COMPLETED <")
    print(f"Total unique genes identified with at least 1 occurrence: {len(df_unified)}")
    print(f"Consolidated file saved successfully at: {output_file_path}")

if __name__ == "__main__":
    main()